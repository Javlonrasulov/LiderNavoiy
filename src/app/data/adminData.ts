export const USER_ROLE_CANONICAL = [
  'Savdo agenti',
  'Dostavkachi/Shofyor',
  'Ofis xodimi',
  'Menedjer',
] as const;

const USER_ROLE_T_KEYS: Record<string, string> = {
  'Savdo agenti': 'userRoleTradeAgent',
  'Dostavkachi/Shofyor': 'userRoleDeliveryDriver',
  'Ofis xodimi': 'userRoleOffice',
  'Menedjer': 'userRoleManager',
};

export function translateUserRole(role: string, t: Record<string, string>): string {
  const key = USER_ROLE_T_KEYS[role];
  return key ? (t[key] || role) : role;
}

export function getUserRoleOptions(t: Record<string, string>): string[] {
  return USER_ROLE_CANONICAL.map(r => translateUserRole(r, t));
}

