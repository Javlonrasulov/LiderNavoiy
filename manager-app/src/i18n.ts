export const t = { uzc, uzl, ru }
export type Translations = typeof uzc

/** Backend validation xabarlarini foydalanuvchi tiliga o‘giradi */
export function localizeApiError(message: string, tr: Translations): string {
  const text = message.trim()
  if (!text) return tr.loginError

  if (text === 'SESSION_ACTIVE' || text.startsWith('SESSION_ACTIVE:')) {
    const device = text.startsWith('SESSION_ACTIVE:')
      ? text.slice('SESSION_ACTIVE:'.length).trim()
      : ''
    return device
      ? tr.sessionActiveDevice.replace('{device}', device)
      : tr.sessionActive
  }

  const unknown = text.match(/^property\s+(\w+)\s+should not exist$/i)
  if (unknown) {
    return tr.apiUnknownField.replace('{field}', unknown[1])
  }

  // Nest ba'zan massivni vergul bilan qo‘shib yuboradi
  const multi = text.split(/,\s*/).map(s => s.trim()).filter(Boolean)
  if (multi.length > 1 && multi.every(s => /^property\s+\w+\s+should not exist$/i.test(s))) {
    return multi
      .map(s => localizeApiError(s, tr))
      .join('; ')
  }

  return text
}

export function loadLang(): Lang {
  const v = localStorage.getItem('lm-lang')
  if (v === 'uzc' || v === 'uzl' || v === 'ru') return v
  // migrate old keys
  if (v === 'uz') return 'uzl'
  return 'uzc'
}
